/**
 * Looping menggunakan for.
 * Menampilkan angka 1 sampai 10.
 */

for (let i = 1; i <= 10; i++) {
    console.log(`perulangan ke-${i}`);
}

/**
 * Looping menggunakan while.
 * Membuat kondisi untuk batasan looping.
 */

let i = 1;
while (i <= 11) {
    console.log(`perulangan ke-${i}`);
    // melakukan increment
    i++;
}
