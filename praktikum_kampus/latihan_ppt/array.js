// Array
const animals = [
    'Mammoth',
    'Brontosaurus',
    'T-rex',
    'Megalodon',
    'Mosasaurus',
    'Pterodactylus',
];

// Menggunakan loop
for (const animal of animals) {
    console.log(`Hewan: ${animal}`);
}

// Tanpa loop
console.log(`Beberapa hewan: ${animals[2]}, ${animals[3]}`);
